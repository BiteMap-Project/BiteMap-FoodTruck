-- Private address book. Stops and order pickups remain independent snapshots.
CREATE TABLE operator_saved_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id BIGINT NOT NULL REFERENCES operators(id),
    name VARCHAR(80) NOT NULL CHECK (length(btrim(name)) > 0),
    venue_name VARCHAR(160) NOT NULL CHECK (length(btrim(venue_name)) > 0),
    address VARCHAR(300) NOT NULL CHECK (length(btrim(address)) > 0),
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    time_zone VARCHAR(80) NOT NULL CHECK (valid_stop_time_zone(time_zone)),
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    location_confirmed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE UNIQUE INDEX operator_saved_locations_active_name
    ON operator_saved_locations(operator_id, lower(name)) WHERE NOT archived;
CREATE INDEX operator_saved_locations_owner ON operator_saved_locations(operator_id, id);
